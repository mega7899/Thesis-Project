import { utils, writeFileXLSX, read, writeFile } from 'xlsx';
import { getExtractedStudentNames } from './processImage'

const masterlistFileInput = document.getElementById('masterList');
const submitMasterlistBtn = document.getElementById('send-btn');
const masterlistTableBody = document.getElementById('masterData');
const combinedAttendanceTable = document.getElementById('combineData');
const combinedTableBody = document.getElementById('combineSheetData')
const combineTablesBtn = document.getElementById('combineTable');
const exportExcelBtn = document.getElementById('exportTable');

let currentSectionCode = null;
let parsedMasterlistRows = [];
let latestSheetData = []; // most recent parsed masterlist, read by the buttons bound below

submitMasterlistBtn.addEventListener('click', ()=>{
  console.log('The button has been clicked!');
  processMasterlistWorkbook();
})

// Bound ONCE, at module load — not inside processMasterlistWorkbook(). Previously these
// were attached every time the masterlist was submitted, so clicking "Submit" twice meant
// "Combine Table" rendered the rows twice, three clicks meant three times, and so on.
combineTablesBtn.addEventListener('click', ()=>{
  renderAttendanceTable(latestSheetData, combinedTableBody)
})

exportExcelBtn.addEventListener('click', ()=>{
  const newWorkbook = utils.table_to_book(combinedAttendanceTable);
  writeFile(newWorkbook, "SheetJSTable.xlsx");
})

async function processMasterlistWorkbook() {
  console.log('data file rendering is processing.');

  if (!masterlistFileInput.files.length) {
    console.warn('No masterlist file selected.');
    return;
  }

  parsedMasterlistRows = []; // reset deterministically here, not in the click handler

  try {
    const uploadedFile = masterlistFileInput.files[0];
    const fileArrayBuffer = await uploadedFile.arrayBuffer();
    const workbook = read(fileArrayBuffer);
    const firstWorksheet = workbook.Sheets[workbook.SheetNames[0]];

    // `range: 1` skips only the header row and reads every row that actually has
    // data, however many students there are. The old hardcoded 'A2:B6' assumed
    // exactly 5 rows — any class roster shorter than that (or a blank Section
    // cell inside that range) produced a row with no index [1], which is what
    // crashed on row[1].slice(9). A roster longer than 5 was silently truncated.
    const parsedSheetData = utils.sheet_to_json(firstWorksheet, { header: 1, range: 1 });

    console.log(parsedSheetData);

    parsedSheetData.forEach(row => {
      // Skip rows missing a Name or Section instead of throwing on them.
      if (row[0] === undefined || row[1] === undefined || row[1] === null) {
        console.warn('Skipping incomplete masterlist row:', row);
        return;
      }
      currentSectionCode = String(row[1]).slice(9); // String() guards against numeric cells too
      parsedMasterlistRows.push(row[0], currentSectionCode);
    })

    latestSheetData = parsedSheetData;
    renderAttendanceTable(parsedSheetData, masterlistTableBody);

    console.log(parsedMasterlistRows);
  } catch (error) {
    console.error('Failed to process masterlist workbook:', error);
  }
}

export function getMasterlistData(){
  const masterlistPayload = {
    studentName: parsedMasterlistRows,
    sectionPattern: currentSectionCode
  }
  return masterlistPayload
}

function renderAttendanceTable(sheetData, tableTargetLocation){
  try{
    const extractedData = getExtractedStudentNames();
    const verifiedStudentNames = extractedData.student;
    console.log(verifiedStudentNames);
    console.log(sheetData);

    // Clear rows generated by a previous render (keep the header row and the
    // placeholder <tr> itself) so re-submitting or re-combining doesn't just
    // keep stacking duplicate rows underneath the old ones.
    const table = tableTargetLocation.closest('table');
    table.querySelectorAll('tr').forEach(tr => {
      if (tr !== tableTargetLocation && !tr.querySelector('th')) tr.remove();
    });

    for(let i = 0; i < sheetData.length; i++){
      // Build a real <tr> element instead of inserting bare <td>s as siblings
      // of the placeholder row — <td> outside a <tr> is invalid HTML and
      // browsers may not render or structure it the way you expect.
      const newRow = document.createElement('tr');
      // Same case-sensitivity issue as the OCR matching in processImage.js:
      // compare names lowercased so "Juan Dela Cruz" (masterlist) still
      // matches "juan dela cruz" (however OCR happened to read it).
      const masterlistName = String(sheetData[i][0] ?? '').toLowerCase();
      const ocrMatchedName = String(verifiedStudentNames[i] ?? '').toLowerCase();
      if(masterlistName === ocrMatchedName){
        newRow.innerHTML = `<td>${sheetData[i][1]}</td><td>${sheetData[i][0]}</td><td>Present</td>`;
      }else {
        newRow.innerHTML = `<td>${sheetData[i][1]}</td><td>${sheetData[i][0]}</td>`;
      }
      tableTargetLocation.insertAdjacentElement('beforebegin', newRow);
    }
  }catch(error){
    console.log(error);
  }
}
